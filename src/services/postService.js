import { supabase } from "../supabaseClient";
import normalizePost from "../utils/normalizePost";

/* =========================================================
   CONSTANTS
========================================================= */

const STORAGE_BUCKET = "posts";
const MAX_FILE_SIZE = 10 * 1024 * 1024;
const MAX_CONTENT_LENGTH = 5000;

const POST_TYPES = new Set(["quote", "image", "video"]);

/* =========================================================
   AUTH
========================================================= */

async function getAuthUser() {
  const {
    data: { user },
    error,
  } = await supabase.auth.getUser();

  if (error) {
    throw new Error(error.message || "Authentication failed.");
  }

  if (!user) {
    throw new Error("User not authenticated.");
  }

  return user;
}

/* =========================================================
   VALIDATION
========================================================= */

function validateFile(file) {
  if (!file) return;

  if (!(file instanceof File)) {
    throw new Error("Invalid file.");
  }

  if (file.size <= 0) {
    throw new Error("File is empty.");
  }

  if (file.size > MAX_FILE_SIZE) {
    throw new Error("File exceeds the 10MB limit.");
  }

  const isImage = file.type.startsWith("image/");
  const isVideo = file.type.startsWith("video/");

  if (!isImage && !isVideo) {
    throw new Error("Unsupported file type.");
  }
}

function validatePost({ content = "", file, type }) {
  const cleanContent = String(content ?? "").trim();

  if (!POST_TYPES.has(type)) {
    throw new Error("Invalid post type.");
  }

  if (cleanContent.length > MAX_CONTENT_LENGTH) {
    throw new Error(
      `Content cannot exceed ${MAX_CONTENT_LENGTH} characters.`
    );
  }

  if (type === "quote" && !cleanContent) {
    throw new Error("Quote cannot be empty.");
  }

  if ((type === "image" || type === "video") && !file) {
    throw new Error(`${type} post requires a media file.`);
  }

  if (file) {
    validateFile(file);

    if (type === "image" && !file.type.startsWith("image/")) {
      throw new Error("Image posts require an image file.");
    }

    if (type === "video" && !file.type.startsWith("video/")) {
      throw new Error("Video posts require a video file.");
    }
  }
}

/* =========================================================
   STORAGE
========================================================= */

function getPublicUrl(path) {
  if (!path) return null;

  const { data } = supabase.storage
    .from(STORAGE_BUCKET)
    .getPublicUrl(path);

  return data?.publicUrl ?? null;
}

function getFileExtension(file) {
  const originalName = file?.name || "";
  const extension = originalName.split(".").pop()?.toLowerCase();

  return extension || "bin";
}

/**
 * Storage paths are always generated by us.
 * Never use the original filename directly.
 */
function createStoragePath(userId, file) {
  const extension = getFileExtension(file);

  return `${userId}/${crypto.randomUUID()}.${extension}`;
}

/* =========================================================
   CREATE
========================================================= */

export async function createPost({
  content = "",
  file = null,
  type = "quote",
}) {
  const user = await getAuthUser();

  validatePost({
    content,
    file,
    type,
  });

  let uploadedPath = null;

  try {
    let media = null;

    /* -----------------------------------------
       UPLOAD MEDIA
    ----------------------------------------- */

    if (file) {
      uploadedPath = createStoragePath(user.id, file);

      const { error: uploadError } = await supabase.storage
        .from(STORAGE_BUCKET)
        .upload(uploadedPath, file, {
          upsert: false,
          contentType: file.type,
          cacheControl: "3600",
        });

      if (uploadError) {
        throw uploadError;
      }

      media = {
        kind: type,
        path: uploadedPath,
        url: getPublicUrl(uploadedPath),
      };
    }

    /* -----------------------------------------
       INSERT POST
    ----------------------------------------- */

    const { data, error } = await supabase
      .from("posts")
      .insert({
        user_id: user.id,
        content: String(content ?? "").trim(),
        media,
      })
      .select(`
        id,
        user_id,
        content,
        media,
        style,
        created_at,
        smile_score,
        share_count,
        profiles (
          id,
          username,
          full_name,
          avatar_url
        )
      `)
      .single();

    if (error) {
      throw error;
    }

    return normalizePost(data);
  } catch (error) {
    /*
     * DB insert failed after Storage upload.
     * Remove the orphaned upload immediately.
     */
    if (uploadedPath) {
      const { error: cleanupError } = await supabase.storage
        .from(STORAGE_BUCKET)
        .remove([uploadedPath]);

      if (cleanupError) {
        console.error(
          "[createPost] Storage cleanup failed:",
          cleanupError
        );
      }
    }

    throw new Error(
      error?.message || "Failed to create post."
    );
  }
}

/* =========================================================
   GET USER POSTS
========================================================= */

export async function getPosts({
  userId,
  limit = 12,
  cursor = null,
}) {
  if (!userId) {
    throw new Error("userId is required.");
  }

  const safeLimit = Math.min(
    Math.max(Number(limit) || 12, 1),
    50
  );

  let query = supabase
    .from("posts")
    .select(`
      id,
      user_id,
      content,
      media,
      style,
      created_at,
      smile_score,
      share_count,
      profiles (
        id,
        username,
        full_name,
        avatar_url
      )
    `)
    .eq("user_id", userId)
    .order("created_at", {
      ascending: false,
    })
    .order("id", {
      ascending: false,
    })
    .limit(safeLimit);

  if (cursor) {
    query = query.lt("created_at", cursor);
  }

  const { data, error } = await query;

  if (error) {
    throw new Error(error.message);
  }

  return (data ?? [])
    .map(normalizePost)
    .filter(Boolean);
}

/* =========================================================
   UPDATE
========================================================= */

export async function updatePost(postId, updates) {
  const user = await getAuthUser();

  if (!postId) {
    throw new Error("Post ID is required.");
  }

  if (!updates || typeof updates !== "object") {
    throw new Error("Invalid updates.");
  }

  const content =
    typeof updates.content === "string"
      ? updates.content.trim()
      : "";

  if (content.length > MAX_CONTENT_LENGTH) {
    throw new Error(
      `Content cannot exceed ${MAX_CONTENT_LENGTH} characters.`
    );
  }

  const { data, error } = await supabase
    .from("posts")
    .update({
      content,
    })
    .eq("id", postId)
    .eq("user_id", user.id)
    .select(`
      id,
      user_id,
      content,
      media,
      style,
      created_at,
      smile_score,
      share_count,
      profiles (
        id,
        username,
        full_name,
        avatar_url
      )
    `)
    .single();

  if (error) {
    throw new Error(error.message);
  }

  return normalizePost(data);
}

/* =========================================================
   DELETE
========================================================= */

export async function deletePost(postId) {
  const user = await getAuthUser();

  if (!postId) {
    throw new Error("Post ID is required.");
  }

  /*
   * -------------------------------------------------------
   * STEP 1
   * Get the post first.
   *
   * We need its media.path so we can clean Storage later.
   * We also select smile_score/share_count so this query
   * returns the same canonical post shape as the other
   * post queries.
   * -------------------------------------------------------
   */

  const { data: post, error: fetchError } = await supabase
    .from("posts")
    .select(`
      id,
      user_id,
      content,
      media,
      style,
      created_at,
      smile_score,
      share_count,
      profiles (
        id,
        username,
        full_name,
        avatar_url
      )
    `)
    .eq("id", postId)
    .eq("user_id", user.id)
    .maybeSingle();

  if (fetchError) {
    throw new Error(fetchError.message);
  }

  if (!post) {
    throw new Error(
      "Post not found or you do not have permission to delete it."
    );
  }

  /*
   * -------------------------------------------------------
   * STEP 2
   * Extract Storage path.
   * -------------------------------------------------------
   */

  const storagePath =
    typeof post.media?.path === "string"
      ? post.media.path
      : null;

  /*
   * -------------------------------------------------------
   * STEP 3
   * Delete database row.
   *
   * RLS must ALSO enforce:
   *
   * auth.uid() = user_id
   * -------------------------------------------------------
   */

  const { error: deleteError } = await supabase
    .from("posts")
    .delete()
    .eq("id", postId)
    .eq("user_id", user.id);

  if (deleteError) {
    throw new Error(deleteError.message);
  }

  /*
   * -------------------------------------------------------
   * STEP 4
   * Remove Storage media.
   *
   * If this fails, the post is already deleted.
   * We therefore log the failure rather than telling the
   * user that deletion failed.
   *
   * A production backend should eventually have a cleanup
   * worker for these orphaned files.
   * -------------------------------------------------------
   */

  if (storagePath) {
    const { error: storageError } = await supabase.storage
      .from(STORAGE_BUCKET)
      .remove([storagePath]);

    if (storageError) {
      console.error(
        "[deletePost] Storage cleanup failed:",
        {
          postId,
          storagePath,
          error: storageError,
        }
      );
    }
  }

  return {
    success: true,
    postId,
  };
}

/* =========================================================
   REALTIME
========================================================= */

export function subscribeToPosts(userId, callback) {
  if (!userId || typeof callback !== "function") {
    return () => {};
  }

  const channelName = `posts-realtime:${userId}`;

  const channel = supabase
    .channel(channelName)
    .on(
      "postgres_changes",
      {
        event: "*",
        schema: "public",
        table: "posts",
        filter: `user_id=eq.${userId}`,
      },
      callback
    )
    .subscribe();

  return () => {
    supabase.removeChannel(channel);
  };
}